# ★ ПРАВИЛО ЧТЕНИЯ, ЗАФИКСИРОВАННОЕ ДО ПРОГОНА:
#   ⛔ если A разошёлся с замороженным продом более чем на 2 кривые — замер недействителен
#      (карта не должна влиять на прод-путь вообще);
#   ★ Δ(H − A) ≈ +14 (как на держанной половине §6.156) ⇒ разрыв был УТЕЧКОЙ, и честная цена

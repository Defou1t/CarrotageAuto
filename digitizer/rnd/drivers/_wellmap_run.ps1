# ★★★ СЧИТАЕМ НА ПРОЦЕССОРЕ, А НЕ НА ВИДЕОКАРТЕ — ЭТО ЗАМЕРЕНО, А НЕ ПРЕДПОЧТЕНИЕ.
# Прогон на 20 шардов упирался НЕ в потоки и НЕ в диск (диски 0%), а в GPU: 85% занятости и
# 12.7 из 16.3 ГБ VRAM, потому что карту делили 20 шардов + LM Studio, Chrome, Discord, игра.
# Это ровно патология §6.106. Замер на 24 листах: GPU одним процессом 161с, CPU шестью шардами
# 108с — и это ДО расширения числа шардов.
# ⚠⚠ ПАРИТЕТ ПРОВЕРЕН НА ТОЙ ВЕЛИЧИНЕ, КОТОРУЮ ДОКЛАДЫВАЕМ. Побитово выдача GPU и CPU на пути с
# `rowdec` РАСХОДИТСЯ (0.0-0.1% точек, медиана 1-2px, редкие скачки до 243px) — §6.106 проверял
# паритет СЕЛЕКТОРА, а декодер туда не входил. Но счёт ЧЕСТНЫХ на 24 листах совпал: 14 против 14,
# расхождений 0 листов. ⇒ на CPU переходить можно; побитовое сравнение с замороженными
# GPU-прогонами — нельзя.
$env:CUDA_VISIBLE_DEVICES=''
$N=24
$have=@(Get-ChildItem "$out/ab_*of$N.pkl" -ErrorAction SilentlyContinue).Count
if ($have -eq $N) { "уже посчитано ($have из $N) — ПРОПУСК"; exit }
if (Test-Path $out) { "было $have из $N дампов — чищу и считаю заново"; Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory -Force -Path "$out/logs" | Out-Null
$procs=@()
0..($N-1) | ForEach-Object {
  $a=@('_trace_prod_ab.py',
       '--mode','A:seq=seq_model_d45p.pt,slot=slot_model_g250.npz,gate=frac0.0,sib=2.0',
       '--mode',"H:seq=seq_model_d45p.pt,slot=slot_model_g250.npz,gate=frac0.0,sib=2.0,rowdec=auto5,rdpool=0,rdpick=3,wellmap=$wm",
       '--pools')+$pools+@('--cap','0','--only-from',"$ts/wellmap_sheets.txt",
       '--shard',"$_/$N",'--shard-by-pool','--out',$out)
  $procs += Start-Process -FilePath $py -ArgumentList $a -WorkingDirectory $rnd -WindowStyle Hidden `
    -RedirectStandardOutput "$out/logs/sh$_.log" -RedirectStandardError "$out/logs/sh$_.err" -PassThru
}
"запущено $N шардов честной держанности -> $out"
$procs | Wait-Process
"★ ГОТОВО -> $out"

r"""_relatch_jumpab.py — ВОСПРОИЗВЕДЕНИЕ неудачного эксперимента §6.19 и проверка его диагноза.

§6.19 закрыл правку «не прыгать дальше jump_limit» с выводом: cov рушится до 0-3%, значит
«ветка ближайший-ран — ОСНОВНАЯ рабочая, ран РЕДКО перекрывает предсказание».

Диагностика (_relatch_diag.py) даёт ПРЯМО ПРОТИВОПОЛОЖНОЕ число: ветка cont срабатывает на
75.8% строк. Оба утверждения одновременно верными быть не могут. Гипотеза: обвал cov — не
свойство данных, а БАГ КОАСТА в самой правке. В trace2d коаст сделан так:

    if jump_limit is not None and abs(c - pred) > jump_limit + (b - a):
        x = pred; continue          # ← v НЕ затухает и строка НЕ пишется

x двигается на clip(v) каждую строку, скорость не гасится, перезахвата нет. Один раз войдя в
коаст на скорости, трасса уезжает по инерции и уже не может вернуться — дальше не пишется
ничего. Отсюда cov 0.02 при том, что ран перекрывает предсказание в 76% строк.

Здесь это проверяется тремя прогонами на ОДНОМ И ТОМ ЖЕ стенде:
  A) как в §6.19 — коаст без затухания, без добивки  → должен воспроизвести обвал cov;
  B) + ЗАТУХАНИЕ скорости в коасте                   → x перестаёт убегать;
  C) + ДОБИВКА пропущенных строк интерполяцией       → cov восстанавливается.

РЕЗУЛЬТАТ ПРОГОНА (19.07, jump_limit=30, все 24 кривые) — гипотеза подтвердилась ЧАСТИЧНО:

  | прогон                          | med(med) | med(cov) | честных | между |
  |---------------------------------|----------|----------|---------|-------|
  | БАЗА (прод)                     |    68.3  |   0.99   |  3/24   | 34.0% |
  | A) §6.19 как было               |    29.1  |   0.02   |  0/22   | 45.7% |
  | B) + затухание скорости         |   185.8  |   0.44   |  0/24   | 44.5% |
  | C) + добивка пропущенных строк  |   249.2  |   0.91   |  0/24   | 62.6% |

A воспроизводит §6.19 БИТ-В-БИТ (там 29.1 / 0.02 / честных 0 из 22) — стенд верен.

✅ ЧТО ПОДТВЕРДИЛОСЬ: обвал cov — действительно АРТЕФАКТ КОАСТА. Одно затухание поднимает
   покрытие 0.02 → 0.44, добивка → 0.91. Значит рассуждение §6.19 «cov рухнул ⇒ ран редко
   перекрывает предсказание» — НЕВЕРНЫЙ ВЫВОД ИЗ ВЕРНОГО ЗАМЕРА. Прямой замер: cont = 75.8%.

❌ ЧТО НЕ ПОДТВЕРДИЛОСЬ (важнее): починка коаста НЕ ДАЁТ хорошей трассы — становится ХУЖЕ базы
   (med 68.3 → 249.2, «между кривыми» 34% → 62.6%). Вернув покрытие, мы получили длинные участки
   слепой экстраполяции по пустому месту: своей туши там нет (54.6% уходов — обрыв), и прямая
   линия сквозь обрыв мимо кривой, которая тем временем ушла.

⇒ ИТОГ: практический вердикт §6.19 «правку не включать» УСТОЯЛ, ошибочным было только его
   ОБЪЯСНЕНИЕ. Ни слепой прыжок, ни слепой коаст задачу не решают. Работать может лишь выбор
   ПРАВИЛЬНОГО рана (45.4% уходов — свой ран был рядом) и осмысленный перезахват после обрыва.
   Durable: обвал покрытия сам по себе НЕ доказывает утверждений о частоте ветки — проверяй
   ветку счётчиком, а не следствием.

  python _relatch_jumpab.py [--limit 30]
"""
import sys, argparse
sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
sys.path.insert(0, r"F:\nds\Auto\digitizer\rnd")
import numpy as np
import _relatch_bench as BE

ap = argparse.ArgumentParser()
ap.add_argument("--limit", type=float, default=30.0)
a = ap.parse_args()
LIM = a.limit


def chooser_A(A, B, Cc, pred, x, v, st):
    """Ровно правка §6.19: нашли ближайший, и если он дальше лимита — отказ (коаст)."""
    k = int(np.argmin(np.abs(Cc - pred)))
    if abs(float(Cc[k]) - pred) > LIM + (int(B[k]) - int(A[k])):
        return None
    return k


def _tracer(decay, backfill, slmax=BE.SLMAX, wide_run=BE.WIDE_RUN):
    """Копия BE.trace, но коаст управляемый: скорость гасится, пропуски можно добить."""
    def tracer(rec, csr, H):
        base = rec["base"]
        x = None; v = 0.0; tr = {}; skipped = []
        for y in range(max(0, rec["y0"]), min(H, rec["y1"] + 1)):
            A, B, Cc = BE._runs_at(csr, y)
            if not len(A):
                if x is not None:
                    x = x + float(np.clip(v, -slmax, slmax)); v *= decay
                continue
            if x is None:
                k = int(np.argmin(np.abs(Cc - base)))
                x = float(Cc[k]); v = 0.0; tr[y] = x; continue
            pred = x + float(np.clip(v, -slmax, slmax))
            cont = np.nonzero((A - 2 <= pred) & (pred <= B + 2))[0]
            if len(cont):
                k = int(cont[np.argmin(np.abs(Cc[cont] - pred))])
            else:
                k = int(np.argmin(np.abs(Cc - pred)))
                if abs(float(Cc[k]) - pred) > LIM + (int(B[k]) - int(A[k])):
                    x = pred; v *= decay          # ← ЗАТУХАНИЕ: x перестаёт убегать
                    skipped.append(y)
                    continue
            aa, bb, c = int(A[k]), int(B[k]), float(Cc[k])
            nx = (bb if abs(bb - base) >= abs(aa - base) else aa) if (bb - aa) >= wide_run else c
            v = 0.6 * v + 0.4 * (nx - x); x = float(nx); tr[y] = float(nx)
        if backfill and tr and skipped:
            # ДОБИВКА: пропущенные в коасте строки — линейно между соседними надёжными точками.
            # Без неё cov обваливается ИСКУССТВЕННО: строки не написаны не потому, что кривой нет,
            # а потому что мы отказались гадать. Экстраполяцию за края НЕ делаем.
            ys = np.array(sorted(tr)); xs = np.array([tr[y] for y in ys])
            sk = np.array([y for y in skipped if ys[0] < y < ys[-1]])
            if len(sk):
                for y, xv in zip(sk, np.interp(sk, ys, xs)):
                    tr[int(y)] = float(xv)
        BE._extend_ends(tr, csr, H, slmax)
        return tr
    return tracer


print(f"jump_limit = {LIM:.0f}px\n")
BE.report("БАЗА (прод, без правки)", BE.run_strategy())
BE.report("A) §6.19 как было: коаст без затухания, без добивки", BE.run_strategy(chooser=chooser_A))
BE.report("B) + затухание скорости в коасте", BE.run_strategy(tracer=_tracer(decay=0.6, backfill=False)))
BE.report("C) + добивка пропущенных строк", BE.run_strategy(tracer=_tracer(decay=0.6, backfill=True)))
print("\nЗАМЕРЕНО: A воспроизводит §6.19 бит-в-бит; затухание+добивка поднимают cov 0.02 → 0.91,")
print("т.е. обвал покрытия был АРТЕФАКТОМ КОАСТА, а не свойством данных (cont = 75.8% строк).")
print("НО точность при этом ХУЖЕ базы (med 68.3 → 249.2, «между» 34% → 62.6%): вернув покрытие,")
print("мы получили слепую экстраполяцию сквозь обрывы. Вердикт «правку не включать» — в силе,")
print("неверным было только ОБЪЯСНЕНИЕ. Нужен ВЫБОР правильного рана, а не запрет прыжка.")

r"""_paleink_size.py — СКОЛЬКО ЛЕЖИТ НА ТРЕКАХ С K ≥ 3, ГДЕ ДЕКОДЕР ТЕРЯЕТ НА БЛЕДНОЙ ТУШИ (§6.185).

ОТКУДА ВОПРОС. §6.179 закрыл ВЫБОР: подбор порога исчерпан, зазор держат две противоположные
ошибки, а §6.180-§6.182 закрыли и попытки дать выбору больше контекста. Значит следующий рычаг —
не «кому отдать трек», а КАЧЕСТВО САМОГО ДЕКОДЕРА. У ветки уже есть указание, где именно он течёт:
`_trace_prod_ab.py` (ключ `softfg`, §6.133) — «потолок построчного решения держит ПОКРЫТИЕ: под
пропущенными строками тушь ЕСТЬ, но бледная». И течь эта должна расти с числом линий на треке:
чем гуще пучок, тем чаще строка теряется целиком.

ЧТО СЧИТАЕТ (по честной паре, счёта не тратит). Разбивает треки по K — числу линий, которые
ведёт прод, — и по каждой корзине даёт: прод, декодер, оракул по треку и НЕДОБОР до оракула.
⇒ Отвечает на единственный вопрос, с которого стоит начинать направление: **СКОЛЬКО ТАМ ЛЕЖИТ.**
Мало — направление не стоит прогона; много — стоит, и видно, с какой корзины начинать.

⚠ Это РАЗМЕР, а не причина. «Бледная тушь» — гипотеза §6.133, и она этим стендом НЕ проверяется:
здесь видно только, где недобор, а не отчего он. Проверять причину — отдельным замером на
`softfg=`, и вот его размер как раз и оценивается тут.

  <ComfyUI>\python_embeded\python.exe _paleink_size.py
"""
import sys, argparse, pickle
sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--rows", default=r"F:/nds/output/taskS/pick_learn_honest2.pkl.dump")
a = ap.parse_args()

rows = pickle.load(open(a.rows, "rb"))
K = np.array([r[3]["n_prod"] for r in rows], float)
hA = np.array([r[4] for r in rows], float)
hB = np.array([r[5] for r in rows], float)
orc = np.maximum(hA, hB)
print(f"★ треков {len(rows)}; прод {hA.sum():.0f}, декодер {hB.sum():.0f}, "
      f"оракул по треку {orc.sum():.0f}")

buckets = [(1, 1), (2, 2), (3, 4), (5, 10 ** 6)]
print("\n★★ ПО ЧИСЛУ ЛИНИЙ НА ТРЕКЕ (K = сколько ведёт прод)")
print("| K | треков | прод | декодер | оракул | недобор оракула к лучшему | декодер лучше на |")
tot_gap = 0.0
for lo, hi in buckets:
    m = (K >= lo) & (K <= hi)
    if not m.any():
        continue
    best = max(hA[m].sum(), hB[m].sum())
    gap = orc[m].sum() - best
    tot_gap += gap
    win = int((hB[m] > hA[m]).sum())
    nm = f"{lo}" if lo == hi else (f"{lo}-{hi}" if hi < 10 ** 6 else f"{lo}+")
    print(f"| {nm} | {int(m.sum())} | {hA[m].sum():.0f} | {hB[m].sum():.0f} | {orc[m].sum():.0f} | "
          f"**{gap:.0f}** | {win} треках |")
print(f"★ суммарный недобор до потрекового оракула: {tot_gap:.0f} кривых")

m3 = K >= 3
print(f"\n★★★ ТРЕКИ K ≥ 3 — ТО, ЧТО НАЗВАНО СЛЕДУЮЩИМ НАПРАВЛЕНИЕМ")
print(f"   треков {int(m3.sum())} из {len(rows)} ({100*m3.mean():.1f}%), "
      f"экспертных кривых в них — не считаем, считаем ЧЕСТНЫЕ:")
print(f"   прод {hA[m3].sum():.0f} · декодер {hB[m3].sum():.0f} · оракул {orc[m3].sum():.0f}")
best3 = max(hA[m3].sum(), hB[m3].sum())
print(f"   ⇒ на этих треках недобрано {orc[m3].sum() - best3:.0f} кривых, "
      f"это {100*(orc[m3].sum()-best3)/max(1e-9, tot_gap):.0f}% всего потрекового недобора")
print(f"   ⚠ декодер здесь {'СИЛЬНЕЕ' if hB[m3].sum() > hA[m3].sum() else 'СЛАБЕЕ'} прода "
      f"({hB[m3].sum():.0f} против {hA[m3].sum():.0f}) — направление имеет смысл только если "
      f"чинить ДЕКОДЕР, а не выбирать между путями")

r"""_path_cost.py — ЦЕНА ВТОРОГО ПУТИ ВЕДЕНИЯ ПО ВРЕМЕНИ ЛИСТА (§6.160).

ОТКУДА ВОПРОС. Из трёх возражений против `row_decoder="auto5"` + `rowdec_pick=3` осталось ОДНО —
«цена вдвое: считаются ОБА пути, декодер втрое дороже прода по листу» (`config.py:301`, §6.150).
Оно решает продуктовый вопрос, а замерено НЕ БЫЛО: «втрое» выведено из того, что корпусный прогон
занял ~12 ч против ~10.5 ч у двухрежимного §6.141, — но это прогоны РАЗНОГО объёма работы, и
множитель из них не следует.

⚠⚠ И ПЕРВОЕ, ЧТО НАДО ЗНАТЬ ПРО ЭТУ ЦЕНУ, — ОНА НЕ РЕГУЛИРУЕТСЯ ПОРОГОМ. В `trace2d.trace_auto`
декодер считается БЕЗУСЛОВНО на каждом листе (`alt = rowdec.trace_auto(...)`), и только ПОСЛЕ
этого читается `rowdec_pick`, который выбирает, чей результат оставить ПО ТРЕКУ. ⇒ Никакое
значение `rowdec_pick` работы не убирает; дешевле сделать может только гейт ПО ЛИСТУ, ДО вызова
декодера, а такого в коде нет. Стенд проверяет это по исходнику, а не по памяти.

ЧТО СЧИТАЕТ. Время листа берётся из МЕТОК ВРЕМЕНИ каталогов выдачи: каталог получает mtime, когда
шард дописал его файл, поэтому отсортированные метки прогона — это поток готовых листов. При
известном числе шардов «сумма промежутков / листов * шардов» = секунды на лист. Даётся два числа:
  ПОЛНОЕ    — все промежутки (внутри и простой машины, и паузы регулятора нагрузки);
  АКТИВНОЕ  — без хвоста больше 10 медиан, то есть без стояния.
⚠ Оценщики расходятся там, где прогон упирался не в счёт, а в доступность машины; расхождение
печатается («простой»), и если оно велико, число читать нельзя.

⚠⚠ ГЛАВНАЯ ЛОВУШКА — ПОРЯДОК РЕЖИМА В ПРОГОНЕ. Режимы одного прогона идут последовательно, и
второй работает по прогретому кэшу файлов. Стенд проверяет это ПРЯМО, а не оговаривает: берёт
пары «первый → второй» и смотрит, дешевеет ли второй режим ДАЖЕ КОГДА ОН ТЯЖЕЛЕЕ по работе.
Дешевеет только более лёгкий ⇒ порядок цену не определяет.

⚠ Сравнивать можно только прогоны с ОДИНАКОВЫМ числом шардов и на одном устройстве: `auto5` на
GPU почти бесплатен, на CPU — нет. Устройство в логи не печатается, оно взято из драйвера
(`CUDA_VISIBLE_DEVICES=''` в `.ps1` = CPU) и записано в таблице ниже руками. ЧИСЛО ШАРДОВ руками
НЕ пишется — берётся из знаменателя дампов прогона (первая редакция ошиблась в нём на `ab_fold0`
и выдала недействительную строку). Нет опоры с тем же (устройство, шарды) — строка не печатается.

⚠⚠ И ЕЩЁ ОДНА ЛОВУШКА, ЗАКРЫТАЯ ПОСЛЕ ПРОВЕРКИ: РЕЖИМЫ ОДНОГО ПРОГОНА ИДУТ НЕ СТРОГО
ПОСЛЕДОВАТЕЛЬНО. Шарды рассинхронизируются, и второй режим стартует, пока первый ещё считается
(перекрытие до 87% на CPU-прогонах). ⇒ множитель «×шардов» там держит больше шардов, чем работало,
а колонка «простой» показывает не стояние машины, а уход шардов в другой режим. CPU-строки читать
только как порядок величины: честная парная оценка внутри ОДНОГО процесса даёт для `ab_wellmap`
H/A ×2.4-2.5, а не ×2.0.

⚠⚠ ЖИВОЙ КАТАЛОГ НЕ ЧИТАЕТСЯ. Каталог, дописанный менее `--live` минут назад, помечается ЖИВЫМ и
в выводы не идёт: его числа между запусками стенда МЕНЯЮТСЯ. Первая редакция §6.160 записала
строку `ab_pickmodel f1` на недосчитанном фолде, и тот же стенд на том же коде даёт на ней другое число.

  <ComfyUI>\python_embeded\python.exe _path_cost.py
"""
import sys, argparse
sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
from pathlib import Path
import numpy as np

LIVE_MIN = 30      # каталог, дописанный менее LIVE_MIN минут назад, считается ЖИВЫМ

ap = argparse.ArgumentParser()
ap.add_argument("--src", default=r"F:/nds/Auto/auto/trace2d.py", help="исходник ворот выбора пути")
ap.add_argument("--min-sheets", type=int, default=20)
ap.add_argument("--live", type=int, default=LIVE_MIN,
                help="минут: каталог, дописанный позже, считается ЖИВЫМ и в выводы не идёт")
a = ap.parse_args()

# (подпись, каталог режима, устройство, порядок режима в прогоне)
# ⚠⚠ ЧИСЛО ШАРДОВ РУКОЙ НЕ ПИШЕТСЯ. В первой редакции стенда оно было записано в таблице, и у
# `ab_fold0` стояло 24 вместо 10 (драйвер `_fold0_run.ps1:23`, `$N=10`) — строка сравнивала
# 10-шардовый прогон с 24-шардовой опорой, и её число было недействительно. Теперь знаменатель
# берётся из имён дампов `ab_*of<N>.pkl`, то есть из артефакта самого прогона.
RUNS = [
    ("ab_rowdec_pair A  прод, ОДИН путь", "F:/nds/output/taskS/ab_rowdec_pair/A", "GPU", "1-й"),
    ("ab_rowdec_pair B  декодер, ОДИН", "F:/nds/output/taskS/ab_rowdec_pair/B", "GPU", "2-й"),
    ("ab_rdpick_c   D  ОБА пути, порог", "F:/nds/output/taskS/ab_rdpick_c/D", "GPU", "один"),
    ("ab_pickmodel f0 M ОБА, обученный", "F:/nds/output/taskS/ab_pickmodel/f0/M", "GPU", "один"),
    ("ab_pickmodel f1 M ОБА, обученный", "F:/nds/output/taskS/ab_pickmodel/f1/M", "GPU", "один"),
    ("ab_pickmodel f2 M ОБА, обученный", "F:/nds/output/taskS/ab_pickmodel/f2/M", "GPU", "один"),
    ("ab_wellmap    A  прод, ОДИН путь", "F:/nds/output/taskS/ab_wellmap/A", "CPU", "1-й"),
    ("ab_wellmap    H  ОБА пути", "F:/nds/output/taskS/ab_wellmap/H", "CPU", "2-й"),
    ("ab_fold0      A  прод, ОДИН путь", "F:/nds/output/taskS/ab_fold0/A", "CPU", "1-й"),
    ("ab_fold0      H  ОБА пути", "F:/nds/output/taskS/ab_fold0/H", "CPU", "2-й"),
]



def shards(mode_dir):
    """→ число шардов из знаменателя дампов прогона (`ab_*of<N>.pkl` в каталоге ПРОГОНА)."""
    run = Path(mode_dir).parent
    ns = {f.stem.split("of")[1] for f in run.glob("ab_*of*.pkl")}
    if len(ns) == 1:
        return int(ns.pop())
    logs = list((run / "logs").glob("sh*.log"))
    return len(logs) or 0


# ★★ ПРОВЕРКА ПО ИСХОДНИКУ, А НЕ ПО ПАМЯТИ: считается ли декодер ДО чтения `rowdec_pick`.
print("★ ГДЕ ТРАТИТСЯ ВРЕМЯ: ворота выбора пути в исходнике")
try:
    src = Path(a.src).read_text(encoding="utf-8")
    i_call = src.index("alt = rowdec.trace_auto(")
    i_pick = src.index('pick = int(getattr(p, "rowdec_pick"')
    ln = lambda k: src[:k].count("\n") + 1
    print(f"   вызов декодера      {Path(a.src).name}:{ln(i_call)}")
    print(f"   чтение rowdec_pick  {Path(a.src).name}:{ln(i_pick)}")
    if i_call < i_pick:
        print("   ⇒ ★ ДЕКОДЕР СЧИТАЕТСЯ БЕЗУСЛОВНО, ДО порога. Порог выбирает результат ПО ТРЕКУ")
        print("     и работы НЕ УБИРАЕТ: цена второго пути порогом `rowdec_pick` не регулируется.")
    else:
        print("   ⇒ ⚠ ПОРЯДОК ИЗМЕНИЛСЯ — перечитать ворота, вывод стенда мог устареть")
except (OSError, ValueError) as e:
    print(f"   ⚠ исходник не разобран ({type(e).__name__}) — вывод про ворота НЕ СДЕЛАН")


def cost(d, n, now):
    """→ секунды на лист по меткам времени каталогов выдачи, полные и активные.
    `live` — каталог ещё дописывается, его числа между запусками стенда МЕНЯЮТСЯ."""
    p = Path(d)
    ts = sorted(x.stat().st_mtime for x in p.iterdir() if x.is_dir()) if p.is_dir() else []
    if len(ts) < a.min_sheets or not n:
        return None
    g = np.diff(np.array(ts))
    med = float(np.median(g))
    keep = g[g <= 10 * med]
    return dict(n=len(ts), span=(ts[-1] - ts[0]) / 3600.0, live=(now - ts[-1]) < a.live * 60,
                full=float(g.sum()) / len(g) * n,
                act=float(keep.sum()) / len(keep) * n,
                stall=1.0 - float(keep.sum()) / float(g.sum()) if g.sum() else 0.0)


import time
now = time.time()
print("\n★ ЦЕНА ЛИСТА ПО МЕТКАМ ВРЕМЕНИ (секунд на лист при своём числе шардов)")
print(f"{'прогон / режим':<35}{'листов':>7}{'шард':>5}{'дев':>5}{'реж':>5}"
      f"{'полное':>9}{'активное':>10}{'простой':>9}{'span,ч':>8}{'':>7}")
R, NSH = {}, {}
for nm, d, dev, order in RUNS:
    n = shards(d)
    c = cost(d, n, now)
    if c is None:
        print(f"{nm:<35}   — нет каталога, мало листов или не найдено число шардов")
        continue
    R[nm] = (c, dev, order)
    NSH[nm] = n
    flag = "  ⚠ЖИВОЙ" if c["live"] else ""
    print(f"{nm:<35}{c['n']:>7}{n:>5}{dev:>5}{order:>5}"
          f"{c['full']:>9.0f}{c['act']:>10.0f}{c['stall']*100:>8.0f}%{c['span']:>8.1f}{flag}")
live = [k for k in R if R[k][0]["live"]]
if live:
    print(f"   ⚠⚠ ЖИВЫЕ КАТАЛОГИ ({', '.join(x.split()[1] for x in live)}) — их числа между запусками")
    print(f"      стенда МЕНЯЮТСЯ; в выводы ниже они НЕ ИДУТ. Первая редакция §6.160 записала")
    print(f"      строку `ab_pickmodel f1` на НЕДОСЧИТАННОМ фолде и не воспроизводилась потом.")

# ★ ЛОВУШКА ПОРЯДКА: дешевеет ли второй режим, когда он ТЯЖЕЛЕЕ первого.
print("\n★ ПРОБА НА ПРОГРЕТЫЙ КЭШ (пары одного прогона; второй режим работает по тёплым файлам)")
PROBE = [("ab_rowdec_pair A  прод, ОДИН путь", "ab_rowdec_pair B  декодер, ОДИН",
          "второй ЛЕГЧЕ по работе"),
         ("ab_wellmap    A  прод, ОДИН путь", "ab_wellmap    H  ОБА пути",
          "второй ТЯЖЕЛЕЕ по работе"),
         ("ab_fold0      A  прод, ОДИН путь", "ab_fold0      H  ОБА пути",
          "второй ТЯЖЕЛЕЕ по работе")]
heavier = []
for x, y, what in PROBE:
    if x in R and y in R:
        r = R[y][0]["act"] / R[x][0]["act"]
        print(f"   {what:<26} 2-й / 1-й = x{r:.2f}")
        if "ТЯЖЕЛЕЕ" in what:
            heavier.append(r)
if heavier and min(heavier) > 1.0:
    print("   ⇒ ★ ПОРЯДОК ЦЕНУ НЕ ОПРЕДЕЛЯЕТ: второй режим, который тяжелее, и меряется тяжелее.")
    print("     Значит дешевизна декодера — свойство пути, а не тёплого кэша.")
else:
    print("   ⇒ ⚠ второй режим дешевеет независимо от работы — числа ниже читать НЕЛЬЗЯ")

# ★ НАДБАВКА ВТОРОГО ПУТИ — только внутри одного устройства и одного числа шардов.
print("\n★ НАДБАВКА ВТОРОГО ПУТИ (оба пути против прода; сравнивать можно только внутри дев+шардов)")
BASE = {("GPU", 8): "ab_rowdec_pair A  прод, ОДИН путь",
        ("CPU", 24): "ab_wellmap    A  прод, ОДИН путь"}
for nm, (c, dev, order) in R.items():
    if "ОБА" not in nm:
        continue
    if c["live"]:
        print(f"   {nm:<35} ⚠ ЖИВОЙ КАТАЛОГ — не читается")
        continue
    b = BASE.get((dev, NSH[nm]))
    if not b or b not in R:
        print(f"   {nm:<35} ⛔ НЕТ ОПОРЫ на {dev} при {NSH[nm]} шардах — сравнивать НЕ С ЧЕМ")
        continue
    print(f"   {nm:<35} x{c['act']/R[b][0]['act']:.2f} акт. / "
          f"x{c['full']/R[b][0]['full']:.2f} полн.   (опора: {b[:14]}, {dev}, {NSH[nm]}ш)")

print("\n⚠ Прогоны сняты в РАЗНЫЕ дни при разной занятости машины; столбец «простой» показывает,")
print("  сколько времени прогон стоял. Это оценка ПОРЯДКА величины, а не измерение секундомером.")
print("⚠ И это цена ЗАМЕРНОГО стенда (8-24 шарда, OMP 2-3), не цена одного листа в проде.")
print("⚠⚠ И РЕЖИМЫ ОДНОГО ПРОГОНА НЕ ИДУТ СТРОГО ПОСЛЕДОВАТЕЛЬНО: шарды рассинхронизируются,")
print("   второй режим стартует, пока первый ещё считается (перекрытие до 87% на CPU-прогонах).")
print("   ⇒ множитель «×шардов» на таких прогонах ЗАВЫШАЕТ число активных шардов, а колонка")
print("   «простой» показывает не стояние машины, а уход шардов в другой режим. CPU-строки")
print("   читать только как порядок величины; честная парная оценка внутри одного процесса")
print("   даёт для `ab_wellmap` H/A ×2.4-2.5, а не ×2.0.")
